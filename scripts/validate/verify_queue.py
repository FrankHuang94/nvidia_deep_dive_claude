#!/usr/bin/env python3
"""Build docs/VERIFY_QUEUE.md: every data row and registry source flagged as entered from memory or
needing re-verification (notes containing recall / recheck / re-verify / unverified / "verify"),
so a session with full network access can clear them systematically.  Usage: verify_queue.py"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "build"))
from common import REPO, read_registry  # noqa: E402

FLAG = re.compile(r"recall|recheck|re-verify|reverify|unverified|as recalled|from memory|verify", re.I)


def main():
    reg, _ = read_registry()
    data_rows = []
    for f in sorted((REPO / "data").glob("*.csv")):
        with f.open(newline="", encoding="utf-8") as fh:
            for n, row in enumerate(csv.DictReader(fh), start=2):
                if FLAG.search(row.get("notes") or ""):
                    key = " · ".join(str(v) for k, v in list(row.items())[:3] if v)
                    data_rows.append((f.name, n, key, row.get("source_id", ""), (row.get("notes") or "")[:140]))
    srcs = [(sid, r) for sid, r in sorted(reg.items(), key=lambda kv: int(kv[0][1:]))
            if FLAG.search(r.get("notes", ""))]
    by_file: dict[str, int] = {}
    for f, *_ in data_rows:
        by_file[f] = by_file.get(f, 0) + 1
    out = [
        "# Verification queue",
        "",
        "Generated by `python3 scripts/validate/verify_queue.py`. Lists every data row and registry source whose",
        "notes say it was entered from memory or needs re-verification. Phase 1–2 research ran in a cloud session",
        "whose network policy blocked direct page fetches (sec.gov, nvidia.com, vendor and analyst sites) and capped",
        "web searches, so these items should be re-checked first in any session with full network access.",
        "",
        f"**{len(data_rows)} data rows** and **{len(srcs)} sources** flagged.",
        "",
        "## Flagged rows by file",
        "",
        "| File | Flagged rows |",
        "|---|---:|",
    ]
    out += [f"| `data/{f}` | {c} |" for f, c in sorted(by_file.items(), key=lambda kv: -kv[1])]
    out += ["", "## Flagged sources", "", "| ID | Title | Publisher | Note |", "|---|---|---|---|"]
    for sid, r in srcs:
        out.append(f"| {sid} | {r.get('title','')[:80].replace('|','/')} | {r.get('publisher','')[:40].replace('|','/')} | "
                   f"{r.get('notes','')[:100].replace('|','/')} |")
    out += ["", "## Flagged data rows", "", "| File | Line | Row key | source_id | Note |", "|---|---:|---|---|---|"]
    for f, n, key, sid, note in data_rows:
        out.append(f"| `{f}` | {n} | {key[:70].replace('|','/')} | {sid} | {note.replace('|','/')} |")
    (REPO / "docs" / "VERIFY_QUEUE.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"verify_queue: {len(data_rows)} rows, {len(srcs)} sources -> docs/VERIFY_QUEUE.md")


if __name__ == "__main__":
    main()
