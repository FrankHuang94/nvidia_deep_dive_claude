#!/usr/bin/env python3
"""Generate glossary.md from docs/glossary/*.csv (columns: term, slug, definition, see_also).

Fragments are merged in filename order; the first definition of a slug wins (00-core.csv first).
Link to a term from any content page with  [HBM](glossary:hbm)  (normalised by `make build`).
Usage: glossary.py [--check]
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import REPO  # noqa: E402

SRC = REPO / "docs" / "glossary"


def collect():
    terms: dict[str, dict] = {}
    problems = []
    for f in sorted(SRC.glob("*.csv")):
        with f.open(newline="", encoding="utf-8") as fh:
            for n, row in enumerate(csv.DictReader(fh), start=2):
                slug = (row.get("slug") or "").strip()
                term = (row.get("term") or "").strip()
                if not slug or not term or not re.fullmatch(r"[a-z0-9\-]+", slug):
                    problems.append(f"{f.name}:{n}: bad slug/term {slug!r}/{term!r}")
                    continue
                if slug in terms:
                    continue
                terms[slug] = {"term": term, "definition": (row.get("definition") or "").strip(),
                               "see_also": (row.get("see_also") or "").strip(), "file": f.name}
    return terms, problems


def render() -> str:
    terms, problems = collect()
    order = sorted(terms.items(), key=lambda kv: kv[1]["term"].lower().lstrip("#0123456789"))
    letters = []
    for _, t in order:
        c = t["term"][0].upper()
        c = c if c.isalpha() else "#"
        if c not in letters:
            letters.append(c)
    out = ["# Glossary", "",
           f"{len(terms)} terms used across the repository, each defined in plain English for a technically",
           "literate (not engineering) reader. Generated by `make build` from `docs/glossary/*.csv`.", "",
           "Jump to: " + " · ".join(f"[{c}](#{c.lower() if c != '#' else 'numbers'})" for c in letters), ""]
    if problems:
        out += ["> [!WARNING]", "> Glossary problems: " + "; ".join(problems[:10]), ""]
    current = None
    for slug, t in order:
        c = t["term"][0].upper()
        c = c if c.isalpha() else "#"
        if c != current:
            current = c
            out += [f"## {c if c != '#' else 'Numbers'}", ""] if c != "#" else ["<a id=\"numbers\"></a>", "## 0–9", ""]
        see = ""
        if t["see_also"]:
            refs = [s.strip() for s in re.split(r"[;,]", t["see_also"]) if s.strip()]
            links = [f"[{terms[s]['term']}](#{s})" if s in terms else s for s in refs]
            see = " *See also:* " + ", ".join(links) + "."
        out.append(f"- <a id=\"{slug}\"></a>**{t['term']}** — {t['definition']}{see}")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv):
    target = REPO / "glossary.md"
    new = render()
    if "--check" in argv:
        if not target.exists() or target.read_text(encoding="utf-8") != new:
            print("glossary: glossary.md is stale (run `make build`)")
            return 1
        print("glossary: up to date")
        return 0
    target.write_text(new, encoding="utf-8")
    print("glossary: wrote glossary.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
