#!/usr/bin/env python3
"""Generate sources/bibliography.md from sources/registry/*.csv.

Usage: bibliography.py [--check]
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import REPO, read_registry  # noqa: E402

RANGES = [
    (1, 999, "Data foundation (data/*.csv)"),
    (1000, 1999, "Synthesis: README, 00 Executive Summary, 01 Flywheel, Cheat Sheet"),
    (2000, 13999, "Layer chapters 02–13"),
    (14000, 19999, "Cross-cutting chapters 14–19"),
    (21000, 27999, "Case studies CS1–CS7"),
    (31000, 35999, "Primers P1–P5"),
    (90000, 99999, "QA and refresh additions"),
]


def esc(s: str) -> str:
    return (s or "").replace("|", "/").replace("\n", " ").strip()


def render() -> str:
    reg, errors = read_registry()
    ids = sorted(reg, key=lambda s: int(s[1:]))
    out = [
        "# Bibliography",
        "",
        "Every numbered citation `[S…]` in this repository resolves here. Generated by `make build` from",
        "`sources/registry/*.csv` — edit those files, not this page. Columns: id, title, publisher,",
        "author, publication date, URL, date accessed.",
        "",
        f"**{len(ids)} sources.** Source types: filing, transcript, keynote, press-release, blog, docs,",
        "whitepaper, paper, analyst, news, dataset.",
        "",
    ]
    if errors:
        out += ["> [!WARNING]", "> Registry problems: " + "; ".join(errors[:10]), ""]
    for lo, hi, label in RANGES:
        block = [s for s in ids if lo <= int(s[1:]) <= hi]
        if not block:
            continue
        out += [f"## {label}", "", "| ID | Title | Publisher | Author | Date | Type | Accessed |", "|---|---|---|---|---|---|---|"]
        for sid in block:
            r = reg[sid]
            title = esc(r.get("title"))
            url = (r.get("url") or "").strip()
            title_cell = f"[{title}]({url})" if url else title
            out.append(f"| <a id=\"{sid.lower()}\"></a>**{sid}** | {title_cell} | {esc(r.get('publisher'))} | "
                       f"{esc(r.get('author'))} | {esc(r.get('date'))} | {esc(r.get('type'))} | {esc(r.get('accessed'))} |")
        out.append("")
    other = [s for s in ids if not any(lo <= int(s[1:]) <= hi for lo, hi, _ in RANGES)]
    if other:
        out += ["## Other", "", "| ID | Title | Publisher | Author | Date | Type | Accessed |", "|---|---|---|---|---|---|---|"]
        for sid in other:
            r = reg[sid]
            out.append(f"| <a id=\"{sid.lower()}\"></a>**{sid}** | [{esc(r.get('title'))}]({r.get('url','')}) | "
                       f"{esc(r.get('publisher'))} | {esc(r.get('author'))} | {esc(r.get('date'))} | {esc(r.get('type'))} | {esc(r.get('accessed'))} |")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv):
    target = REPO / "sources" / "bibliography.md"
    new = render()
    if "--check" in argv:
        if not target.exists() or target.read_text(encoding="utf-8") != new:
            print("bibliography: sources/bibliography.md is stale (run `make build`)")
            return 1
        print("bibliography: up to date")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(new, encoding="utf-8")
    print(f"bibliography: wrote {target.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
